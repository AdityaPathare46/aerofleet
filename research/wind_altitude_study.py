"""How often does a mission pass on ground-level wind but fail on the wind at cruise height? (Pune)

  python -m research.wind_altitude_study        -> research/results/wind_altitude_study.md

Data: Open-Meteo hourly wind at 10 / 80 / 120 / 180 m for Pune's centre over the last 30 days (their
`past_days` archive of forecast-model output — model values, not measurements at a mast). Missions: an
out-and-back of 3 km each way, flown north-south and east-west, 1 kg payload, cruise heights 60 / 100 /
120 m. The battery is sized to the still-air energy plus a margin of 10 / 20 / 30 %, which is the only
free choice — so results are given for each. Energy model and its limits: aerofleet/assurance/wind.py.
"""
from __future__ import annotations

import statistics
from collections import Counter
from pathlib import Path

from aerofleet.assurance.reconcile import Plan
from aerofleet.assurance.wind import fetch_profiles, mission_energy, wind_at, wind_check

CENTRE = (18.5204, 73.8567)
LEG_KM, PAYLOAD_KG, DAYS = 3.0, 1.0, 30
HEIGHTS, MARGINS = (60.0, 100.0, 120.0), (0.10, 0.20, 0.30)


def out_and_back(bearing: str, alt: float) -> Plan:
    dlat, dlon = (LEG_KM * 1000 / 111_320.0, 0.0) if bearing == "N-S" else (0.0, LEG_KM * 1000 / (111_320.0 * 0.9483))
    dest = (CENTRE[0] + dlat, CENTRE[1] + dlon)
    return Plan(CENTRE, [(*CENTRE, 0.0), (*CENTRE, alt), (*dest, alt), (*CENTRE, alt), (*CENTRE, 0.0)], [])


def pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f}%"


def main() -> None:
    hours = fetch_profiles(*CENTRE, past_days=DAYS, forecast_days=0)
    lines = ["# Wind at cruise height against ground-level wind — Pune", "",
             f"Generated by `python -m research.wind_altitude_study`. {len(hours)} hourly forecast-model values from Open-Meteo, "
             f"{hours[0][0]} to {hours[-1][0]} UTC. Model output, not mast measurements.", "",
             "## How much stronger is the wind aloft?", "",
             "| Height | Median wind (m/s) | 90th percentile (m/s) | Median ratio to 10 m | 90th percentile ratio | Hours above 8 m/s |",
             "|---|---|---|---|---|---|"]
    ground = [p[10][0] for _, p in hours]
    lines.append(f"| 10 m | {statistics.median(ground):.1f} | {statistics.quantiles(ground, n=10)[8]:.1f} | 1.00 | 1.00 | {pct(sum(g > 8 for g in ground), len(hours))} |")
    for h in HEIGHTS:
        speeds = [wind_at(p, h)[0] for _, p in hours]
        ratios = [s / g for s, g in zip(speeds, ground) if g > 0.5]
        lines.append(f"| {h:.0f} m | {statistics.median(speeds):.1f} | {statistics.quantiles(speeds, n=10)[8]:.1f} | "
                     f"{statistics.median(ratios):.2f} | {statistics.quantiles(ratios, n=10)[8]:.2f} | {pct(sum(s > 8 for s in speeds), len(hours))} |")
    lines += ["", f"Ratios use the {sum(g > 0.5 for g in ground)} hours with more than 0.5 m/s at 10 m.", "",
              "## Missions that a ground-wind check would pass but the wind aloft fails", "",
              f"Out-and-back, {LEG_KM:.0f} km each way, {PAYLOAD_KG:.0f} kg payload, both orientations pooled ({2 * len(hours)} mission-hours per row).", "",
              "| Cruise height | Battery margin over still air | Pass | Fails only at altitude | Fails on ground wind too |", "|---|---|---|---|---|"]
    for h in HEIGHTS:
        for margin in MARGINS:
            tally: Counter = Counter()
            for bearing in ("N-S", "E-W"):
                plan = out_and_back(bearing, h)
                usable = mission_energy(plan, PAYLOAD_KG)["energy_wh"] * (1 + margin)
                for _, prof in hours:
                    tally[wind_check(plan, PAYLOAD_KG, usable, prof)["verdict"]] += 1
            n = sum(tally.values())
            lines.append(f"| {h:.0f} m | {margin * 100:.0f}% | {pct(tally['PASS'], n)} | {pct(tally['FAILS_AT_ALTITUDE'], n)} | {pct(tally['FAIL'], n)} |")
    lines += ["", "Limits: one location and one month; forecast-model wind; constant 12 m/s airspeed and constant cruise power; "
              "climb, hover and gusts not modelled; the battery margin is an assumption, so each row is conditional on it."]
    out = Path("research/results/wind_altitude_study.md")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
